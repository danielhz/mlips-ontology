#!/usr/bin/env python3
"""Data-set registry for the per-paper KG (see artifacts/kg/DATASETS.md).

Inputs (hand-maintained):
  artifacts/kg/datasets-registry.csv  one row per original, shared data set
  artifacts/kg/origin-papers.csv      papers that introduce a registered
                                      data set but are not in the corpus

Outputs (generated; do not edit):
  artifacts/kg/shared/datasets.ttl       the shared data-set entities
  artifacts/kg/shared/origin-papers.ttl  bibliographic stubs (article only)
  artifacts/kg/datasets-splits.csv       paper-local data set -> registry key

The paper-local mlips:TrainingDataset nodes are neither renamed nor
changed. Which registered data set a paper-local node is a split,
subset or combination of is recorded in datasets-splits.csv only, by
matching the `aliases` (and `exclude`) regular expressions of the
registry against the node's label; no triple links the two until the
schema has a predicate for it.

Usage: datasets_registry.py [--check]
  --check  write nothing; exit 1 if a generated file is missing or stale.
Prints a coverage report either way.
"""
import collections
import csv
import glob
import io
import os
import re
import sys

import rdflib
from rdflib.namespace import RDF, RDFS

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
KG = os.path.join(ROOT, "artifacts", "kg")
MLIPS = rdflib.Namespace("https://w3id.org/mlips#")
SCHEMA = "https://schema.org/"
ENTITY = "https://w3id.org/mlips/entity/"
HEADER = """# GENERATED by artifacts/scripts/datasets_registry.py from
# artifacts/kg/{src}. Do not edit; edit the CSV and run
# `make datasets-registry`. See artifacts/kg/DATASETS.md.

@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix schema: <https://schema.org/> .
@prefix mlips: <https://w3id.org/mlips#> .
@prefix entity: <https://w3id.org/mlips/entity/> .
"""


def lit(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_csv(name):
    with open(os.path.join(KG, name), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def load_papers():
    """paper-id -> (graph, article IRI or None)."""
    out = {}
    for path in sorted(glob.glob(os.path.join(KG, "papers", "*.ttl"))):
        g = rdflib.Graph().parse(path)
        art = next(iter(g.subjects(RDF.type, rdflib.URIRef(SCHEMA + "ScholarlyArticle"))), None)
        out[os.path.basename(path)[:-4]] = (g, art)
    return out


def origin_iri(key, papers):
    if key in papers and papers[key][1] is not None:
        return str(papers[key][1])
    return ENTITY + "article-" + key


def build_origin_ttl(origins):
    lines = [HEADER.format(src="origin-papers.csv"),
             "# Origin-paper stubs: papers that introduce a registered data set and are",
             "# not in the corpus. Article entity only (no mlips:BenchmarkStudy), which",
             "# is what tells a stub from a bibliographic-only paper of the corpus.", ""]
    for o in origins:
        lines += [f"entity:article-{o['key']} a schema:ScholarlyArticle ;",
                  f"    rdfs:label {lit(o['cite_as'] + ' (' + o['year'] + '): ' + o['title'])} ;",
                  f"    schema:name {lit(o['title'])} ;",
                  f"    schema:datePublished \"{o['year']}\"^^xsd:gYear ;",
                  f"    schema:sameAs <https://doi.org/{o['doi']}> ;",
                  f"    rdfs:comment {lit('Origin-paper stub: introduces ' + o['introduces'].replace('|', ' and ') + '; not part of the encoded corpus (bibliographic entry only, ' + o['venue'] + ').')} .",
                  ""]
    return "\n".join(lines)


def build_datasets_ttl(registry, papers):
    lines = [HEADER.format(src="datasets-registry.csv"),
             "# Shared data-set entities: one per original data set. Paper-local",
             "# mlips:TrainingDataset nodes (splits, subsets, combinations) are mapped",
             "# to these in artifacts/kg/datasets-splits.csv, not by a triple.", ""]
    for d in registry:
        defined_elsewhere = any(
            (rdflib.URIRef(ENTITY + d["iri"]), RDF.type, MLIPS.TrainingDataset) in g
            for g, _ in papers.values())
        po = []
        if not defined_elsewhere:
            po.append("a mlips:TrainingDataset")
            po.append(f"rdfs:label {lit(d['label'])}")
            if d["size"]:
                po.append(f"mlips:numConfigurations \"{int(d['size'])}\"^^xsd:integer")
        po.append(f"schema:citation <{origin_iri(d['origin'], papers)}>")
        if d["location"]:
            po.append(f"schema:url <{d['location']}>")
        notes = []
        if d["level_of_theory"]:
            notes.append(f"Reference level: {d['level_of_theory']} (as stated in {d['level_source']}).")
        if d["size"] and not defined_elsewhere:
            notes.append(f"Size as stated in {d['size_source']}.")
        if d["note"]:
            notes.append(d["note"][0].upper() + d["note"][1:] + ".")
        if notes and not defined_elsewhere:
            po.append(f"rdfs:comment {lit(' '.join(notes))}")
        lines.append(f"entity:{d['iri']} " + " ;\n    ".join(po) + " .\n")
    return "\n".join(lines)


def build_splits(registry, papers):
    rows = []
    reg_iris = {ENTITY + d["iri"]: d["key"] for d in registry}
    for pid, (g, _) in papers.items():
        for ds in sorted(g.subjects(RDF.type, MLIPS.TrainingDataset), key=str):
            label = str(g.value(ds, RDFS.label) or "")
            n = g.value(ds, MLIPS.numConfigurations)
            keys = []
            for d in registry:
                if d["exclude"] and re.search(d["exclude"], label):
                    continue
                if re.search(d["aliases"], label):
                    keys.append(d["key"])
            if str(ds) in reg_iris:
                relation, keys = "original", [reg_iris[str(ds)]]
            elif not keys:
                relation = ""
            elif len(keys) > 1:
                relation = "combination"
            elif pid == next(d["origin"] for d in registry if d["key"] == keys[0]):
                relation = "original-or-part (origin paper)"
            else:
                relation = "split-or-subset"
            rows.append([pid, str(ds)[len(ENTITY):], label, str(n) if n is not None else "",
                         "|".join(keys), relation])
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["paper_id", "local_iri", "label", "numConfigurations", "registry_keys", "relation"])
    w.writerows(rows)
    return buf.getvalue(), rows


def main():
    check = "--check" in sys.argv[1:]
    registry, origins = read_csv("datasets-registry.csv"), read_csv("origin-papers.csv")
    papers = load_papers()
    known = set(papers) | {o["key"] for o in origins}
    for d in registry:
        if d["origin"] not in known:
            print(f"registry row {d['key']}: origin {d['origin']} is neither a corpus paper nor a stub")
            return 1
    splits_csv, rows = build_splits(registry, papers)
    outputs = {
        os.path.join(KG, "shared", "datasets.ttl"): build_datasets_ttl(registry, papers),
        os.path.join(KG, "shared", "origin-papers.ttl"): build_origin_ttl(origins),
        os.path.join(KG, "datasets-splits.csv"): splits_csv,
    }
    stale = 0
    for path, text in outputs.items():
        rdflib.Graph().parse(data=text, format="turtle") if path.endswith(".ttl") else None
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale += 1
            if check:
                print(f"stale or missing: {os.path.relpath(path, ROOT)}")
            else:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(text)

    matched = [r for r in rows if r[4]]
    print(f"{len(registry)} registered data sets, {len(origins)} origin-paper stubs")
    print(f"{len(rows)} paper-local data-set nodes in {len({r[0] for r in rows})} papers; "
          f"{len(matched)} mapped to a registered data set ({len({r[0] for r in matched})} papers)\n")
    print("| data set | nodes | papers | origin |")
    print("|---|---|---|---|")
    per = collections.defaultdict(list)
    for r in matched:
        for k in r[4].split("|"):
            per[k].append(r[0])
    for d in registry:
        print(f"| {d['key']} | {len(per[d['key']])} | {len(set(per[d['key']]))} | {d['origin']} |")
    stems = collections.Counter()
    by_stem = collections.defaultdict(set)
    for r in rows:
        if not r[4]:
            stem = re.split(r"[:(,]| training| data| subset| split| test", r[2])[0].strip()
            stems[stem] += 1
            by_stem[stem].add(r[0])
    multi = [(s, n, len(by_stem[s])) for s, n in stems.most_common() if len(by_stem[s]) > 1]
    print("\nUnmapped label stems used by more than one paper (candidates for the registry):")
    for s, n, p in multi[:25]:
        print(f"  {s}: {n} nodes, {p} papers")
    print(f"\n{stale} generated file(s) {'stale' if check else 'written'}")
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
