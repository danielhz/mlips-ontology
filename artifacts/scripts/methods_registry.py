#!/usr/bin/env python3
"""Method derivation from the method registry (see artifacts/kg/METHODS.md).

Input (hand-maintained):
  artifacts/kg/methods-registry.csv  columns derived_from (registry keys,
                                     |-separated) and derived_from_source
                                     (paper and location that state it)

Output (generated; do not edit):
  artifacts/kg/shared/methods.ttl    one mlips:derivedFromMethod triple per
                                     registry edge, with its source as a
                                     comment, and for every method at either
                                     end of an edge its type and registry
                                     label (the same registry-fixed triples
                                     the paper files repeat), so that no
                                     endpoint is left undeclared

Paper files never assert mlips:derivedFromMethod (`make methods-check`
fails if one does), so the edges live only here, like the shared data
sets of datasets_registry.py.

Usage: methods_registry.py [--check]
  --check  write nothing; exit 1 if the generated file is missing or stale,
           or the registry columns are invalid.
"""
import os
import re
import sys

from check_methods import KG, derivation_errors, load_registry, parents

OUT = os.path.join(KG, "shared", "methods.ttl")
HEADER = """# GENERATED by artifacts/scripts/methods_registry.py from
# artifacts/kg/methods-registry.csv (columns derived_from and
# derived_from_source). Do not edit; edit the CSV and run
# `make methods-registry`. See artifacts/kg/METHODS.md.

@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix mlips: <https://w3id.org/mlips#> .
@prefix entity: <https://w3id.org/mlips/entity/> .

# Method derivation (mlips:derivedFromMethod). An edge is recorded only
# when the paper that introduced the derived method states it; the
# comment above each statement names that paper and the location.
"""


def lit(s):
    """Same literal form as encode_paper.lit, so the triples coincide."""
    s = re.sub(r"\s+", " ", str(s).strip())
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(methods):
    by_key = {m["key"]: m for m in methods.values()}
    out = [HEADER]
    for key in sorted(by_key, key=str.lower):
        m = by_key[key]
        if not parents(m):
            continue
        objs = ", ".join("entity:" + by_key[p]["iri"] for p in parents(m))
        out.append(f"# {key}: stated in {m['derived_from_source']}.")
        out.append(f"entity:{m['iri']} mlips:derivedFromMethod {objs} .\n")
    ends = {k for k, m in by_key.items() if parents(m)} | {p for m in by_key.values() for p in parents(m)}
    out.append("# Method identity of every derivation endpoint (registry-fixed type and\n"
               "# label, identical to the triples the paper files repeat).\n")
    for key in sorted(ends, key=str.lower):
        m = by_key[key]
        out.append(f"entity:{m['iri']} a mlips:MLIPMethod ;\n    rdfs:label {lit(m['label'])} .\n")
    return "\n".join(out)


def main():
    check = sys.argv[1:] == ["--check"]
    methods, _ = load_registry()
    errs = derivation_errors(methods)
    for e in errs:
        print(e)
    if errs:
        return 1
    text = build(methods)
    edges = sum(len(parents(m)) for m in methods.values())
    rel = os.path.relpath(OUT, os.path.dirname(os.path.dirname(KG)))
    if check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
        if current != text:
            print(f"{rel} is stale: run `make methods-registry`")
            return 1
        print(f"{rel} up to date ({edges} derivation edges)")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {rel} ({edges} derivation edges)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
