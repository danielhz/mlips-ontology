#!/usr/bin/env python3
"""Give every mlips:BenchmarkResult in the per-paper KG an rdfs:label.

A result is a reified relation (model x material x metrics) and carried
no label of its own, so a browser listed results by IRI and two results
of one study on the same model and material looked like duplicates.

Label:  "<model label(s)> on <material label>[, <variant>]"

The variant is added only where two results of one file would otherwise
get the same label (training / validation / test errors of one model,
two test sets on one material). It is taken from the result's first
accuracy-metric label, which states the evaluation set: the text after
the first ": " or ", " of that label. If that still does not separate
the results, the variant is dropped and the result's local key is
appended in brackets instead.

The labels are written as one generated block at the end of each file,
between marker comments; a result that already has a label outside the
block keeps it. Re-running replaces the block, so the script is
idempotent and can follow any regeneration of a paper file.

Usage: add_result_labels.py [--check] [paper-id ...]
  --check  write nothing; exit 1 if a file's block is missing or stale.
"""
import collections
import glob
import os
import re
import sys

import rdflib
from rdflib.namespace import RDF, RDFS

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PAPERS = os.path.join(ROOT, "artifacts", "kg", "papers")
MLIPS = rdflib.Namespace("https://w3id.org/mlips#")
ENTITY = "https://w3id.org/mlips/entity/"
BEGIN = "# --- BenchmarkResult labels (generated by artifacts/scripts/add_result_labels.py; do not edit) ---"
END = "# --- end of generated BenchmarkResult labels ---"


def split_block(text):
    i = text.find(BEGIN)
    if i < 0:
        return text.rstrip("\n") + "\n", ""
    j = text.find(END, i)
    tail = text[j + len(END):] if j >= 0 else ""
    return text[:i].rstrip("\n") + "\n" + tail.lstrip("\n"), text[i:j + len(END)] if j >= 0 else text[i:]


def variant(g, r):
    metrics = sorted(g.objects(r, MLIPS.hasAccuracyMetric), key=str)
    for m in metrics:
        lab = g.value(m, RDFS.label)
        if lab is None:
            continue
        lab = str(lab)
        cuts = [k + n for k, n in ((lab.find(": "), 2), (lab.find(", "), 2)) if k - n >= -1 and k >= 0]
        return lab[min(cuts):].strip() if cuts else lab
    return ""


def key_of(r, pid):
    name = str(r)[len(ENTITY):] if str(r).startswith(ENTITY) else str(r)
    name = re.sub(r"^result-", "", name)
    return re.sub(r"-" + re.escape(pid) + r"$", "", name)


def labels_for(body, pid):
    g = rdflib.Graph().parse(data=body, format="turtle")
    todo = [r for r in g.subjects(RDF.type, MLIPS.BenchmarkResult) if g.value(r, RDFS.label) is None]
    base = {}
    for r in todo:
        models = sorted(str(g.value(m, RDFS.label) or key_of(m, pid)) for m in g.objects(r, MLIPS.evaluatesModel))
        mats = sorted(str(g.value(m, RDFS.label) or key_of(m, pid)) for m in g.objects(r, MLIPS.targetMaterial))
        base[r] = " / ".join(models) + " on " + " / ".join(mats)
    out = dict(base)
    for stage in (variant, None):
        count = collections.Counter(out.values())
        for r in todo:
            if count[out[r]] > 1:
                if stage is variant:
                    v = variant(g, r)
                    out[r] = base[r] + (", " + v if v else "")
                else:
                    out[r] = base[r] + " [" + key_of(r, pid) + "]"
    return {r: re.sub(r"\s+", " ", out[r]).strip() for r in todo}


def block_for(body, pid):
    labels = labels_for(body, pid)
    if not labels:
        return ""
    lines = [BEGIN]
    for r in sorted(labels, key=str):
        text = labels[r].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'<{r}> <{RDFS.label}> "{text}" .')
    lines.append(END)
    return "\n".join(lines)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    stale = n_labels = n_files = 0
    for path in sorted(glob.glob(os.path.join(PAPERS, "*.ttl"))):
        pid = os.path.basename(path)[:-4]
        if args and pid not in args:
            continue
        text = open(path, encoding="utf-8").read()
        body, old = split_block(text)
        new = block_for(body, pid)
        n_labels += new.count("\n") - 1 if new else 0
        n_files += 1 if new else 0
        want = body + ("\n" + new + "\n" if new else "")
        if want != text:
            stale += 1
            if check:
                print(f"{pid}: generated result labels missing or stale")
            else:
                open(path, "w", encoding="utf-8").write(want)
    print(f"{n_labels} result labels in {n_files} files; "
          f"{stale} file(s) {'need updating' if check else 'updated'}")
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
